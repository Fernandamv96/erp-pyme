/* ==========================================================
   BASE DE DATOS (PostgreSQL)
   - Con DATABASE_URL (Neon, en Vercel): servidor Postgres real.
   - Sin DATABASE_URL (tu computador): PGlite, un Postgres que
     corre dentro de Node y guarda todo en la carpeta data/pglite.
   ========================================================== */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { MODULOS, NOMBRES_MODULOS } from "./esquemas.js";
import { DATOS_EJEMPLO } from "./datos-ejemplo.js";

const RAIZ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const EN_MEMORIA = process.env.DB_PATH === "memory://";
export const RUTA_DB = process.env.DATABASE_URL
  ? "PostgreSQL (DATABASE_URL)"
  : EN_MEMORIA ? "memory://" : path.resolve(RAIZ, process.env.DB_PATH || "data/pglite");

/* ---------- Conexión ----------
   Las dos opciones exponen lo mismo: consulta(sql, valores) y
   transaccion(fn), donde fn recibe su propia función de consulta. */
async function conectar() {
  if (process.env.DATABASE_URL) {
    const { default: pg } = await import("pg");
    const pool = new pg.Pool({ connectionString: process.env.DATABASE_URL, max: 3 });
    return {
      consulta: (sql, valores) => pool.query(sql, valores),
      async transaccion(fn) {
        const cliente = await pool.connect();
        try {
          await cliente.query("BEGIN");
          const r = await fn((sql, valores) => cliente.query(sql, valores));
          await cliente.query("COMMIT");
          return r;
        } catch (e) {
          await cliente.query("ROLLBACK");
          throw e;
        } finally {
          cliente.release();
        }
      },
      cerrar: () => pool.end()
    };
  }
  const { PGlite } = await import("@electric-sql/pglite");
  if (!EN_MEMORIA) fs.mkdirSync(RUTA_DB, { recursive: true });
  const pglite = new PGlite(RUTA_DB);
  return {
    consulta: (sql, valores) => pglite.query(sql, valores),
    transaccion: fn => pglite.transaction(tx => fn((sql, valores) => tx.query(sql, valores))),
    cerrar: () => pglite.close()
  };
}

let conexion;
const db = () => (conexion ??= conectar());
const filas = async (sql, valores) => (await (await db()).consulta(sql, valores)).rows;
const fila = async (sql, valores) => (await filas(sql, valores))[0];

/* ---------- Creación de tablas a partir del esquema ---------- */
function tipoSQL(regla) {
  if (regla.tipo === "numero") return regla.entero ? "INTEGER NOT NULL DEFAULT 0" : "DOUBLE PRECISION NOT NULL DEFAULT 0";
  return "TEXT NOT NULL DEFAULT ''";
}

async function crearTablas(q) {
  for (const modulo of NOMBRES_MODULOS) {
    const columnas = Object.entries(MODULOS[modulo]).map(([campo, regla]) => `${campo} ${tipoSQL(regla)}`);
    await q(`CREATE TABLE IF NOT EXISTS ${modulo} (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      ${columnas.join(",\n      ")},
      creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
      actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
    )`);
  }
  await q(`CREATE TABLE IF NOT EXISTS configuracion (clave TEXT PRIMARY KEY, valor TEXT NOT NULL)`);
  await q(`CREATE TABLE IF NOT EXISTS intentos_login (ip TEXT NOT NULL, fecha TIMESTAMPTZ NOT NULL DEFAULT now())`);
  await q(`CREATE INDEX IF NOT EXISTS idx_ventas_fecha ON ventas(fecha)`);
  await q(`CREATE INDEX IF NOT EXISTS idx_gastos_fecha ON gastos(fecha)`);
  await q(`CREATE INDEX IF NOT EXISTS idx_intentos_ip ON intentos_login(ip, fecha)`);
}

const columnasDe = modulo => Object.keys(MODULOS[modulo]);
const selectDe = modulo => `SELECT id, ${columnasDe(modulo).join(", ")} FROM ${modulo}`;
const marcadores = n => Array.from({ length: n }, (_, i) => `$${i + 1}`).join(", ");

/* ---------- Operaciones por módulo ---------- */
export function listar(modulo) {
  return filas(`${selectDe(modulo)} ORDER BY id`);
}

export function obtener(modulo, id) {
  return fila(`${selectDe(modulo)} WHERE id = $1`, [id]);
}

export async function crear(modulo, datos) {
  const campos = Object.keys(datos);
  const { id } = await fila(
    `INSERT INTO ${modulo} (${campos.join(", ")}) VALUES (${marcadores(campos.length)}) RETURNING id`,
    campos.map(c => datos[c])
  );
  return obtener(modulo, id);
}

export async function actualizar(modulo, id, datos) {
  const campos = Object.keys(datos);
  const r = await fila(
    `UPDATE ${modulo} SET ${campos.map((c, i) => `${c} = $${i + 1}`).join(", ")}, actualizado_en = now()
     WHERE id = $${campos.length + 1} RETURNING id`,
    [...campos.map(c => datos[c]), id]
  );
  return r ? obtener(modulo, id) : null;
}

export async function eliminar(modulo, id) {
  return Boolean(await fila(`DELETE FROM ${modulo} WHERE id = $1 RETURNING id`, [id]));
}

/* ---------- Configuración (nombre de la empresa) ---------- */
export async function obtenerEmpresa() {
  return (await fila(`SELECT valor FROM configuracion WHERE clave = 'empresa'`))?.valor ?? DATOS_EJEMPLO.empresa;
}

const guardarConfig = (q, clave, valor) =>
  q(`INSERT INTO configuracion (clave, valor) VALUES ($1, $2)
     ON CONFLICT (clave) DO UPDATE SET valor = excluded.valor`, [clave, valor]);

export async function guardarEmpresa(nombre) {
  await guardarConfig((await db()).consulta, "empresa", nombre);
  return nombre;
}

/* ---------- Todo junto (lo que usa el panel) ---------- */
export async function todo() {
  const r = { empresa: await obtenerEmpresa() };
  for (const m of NOMBRES_MODULOS) r[m] = await listar(m);
  return r;
}

/* ---------- Datos de ejemplo ---------- */
async function cargarEjemplo(q) {
  await q(`TRUNCATE ${NOMBRES_MODULOS.join(", ")} RESTART IDENTITY`);
  for (const m of NOMBRES_MODULOS) {
    const campos = columnasDe(m);
    for (const f of DATOS_EJEMPLO[m]) {
      await q(`INSERT INTO ${m} (${campos.join(", ")}) VALUES (${marcadores(campos.length)})`, campos.map(c => f[c]));
    }
  }
  await guardarConfig(q, "empresa", DATOS_EJEMPLO.empresa);
  await guardarConfig(q, "inicializado", new Date().toISOString());
}

export async function restaurarEjemplo() {
  await (await db()).transaccion(cargarEjemplo);
  return todo();
}

/* ---------- Resumen (para reportes o integraciones) ---------- */
export async function resumen() {
  const ventas = await fila(`SELECT COALESCE(SUM(cantidad * precio), 0)::float8 AS total, COUNT(*)::int AS n FROM ventas`);
  const gastos = await fila(`SELECT COALESCE(SUM(monto), 0)::float8 AS total, COUNT(*)::int AS n FROM gastos`);
  const clientes = (await fila(`SELECT COUNT(*)::int AS n FROM clientes`)).n;
  const porMes = await filas(`
    SELECT mes, SUM(v)::float8 AS ventas, SUM(g)::float8 AS gastos FROM (
      SELECT substr(fecha, 1, 7) AS mes, cantidad * precio AS v, 0 AS g FROM ventas
      UNION ALL
      SELECT substr(fecha, 1, 7), 0, monto FROM gastos
    ) t GROUP BY mes ORDER BY mes`);
  const stockBajo = await filas(`SELECT id, producto, stock, minimo FROM inventario WHERE stock <= minimo ORDER BY producto`);
  return {
    ventasTotales: ventas.total,
    gastosTotales: gastos.total,
    resultado: ventas.total - gastos.total,
    numeroVentas: ventas.n,
    numeroGastos: gastos.n,
    clientes,
    ticketPromedio: ventas.n ? Math.round(ventas.total / ventas.n) : 0,
    porMes: porMes.map(m => ({ ...m, resultado: m.ventas - m.gastos })),
    stockBajo
  };
}

/* ---------- Intentos de inicio de sesión (contra fuerza bruta) ----------
   Se guardan en la base porque en Vercel cada llamada puede caer en
   una instancia distinta y la memoria no se comparte. */
export async function intentosRecientes(ip, minutos) {
  return (await fila(
    `SELECT COUNT(*)::int AS n FROM intentos_login WHERE ip = $1 AND fecha > now() - make_interval(mins => $2)`,
    [ip, minutos]
  )).n;
}

export async function registrarIntento(ip) {
  await filas(`INSERT INTO intentos_login (ip) VALUES ($1)`, [ip]);
  await filas(`DELETE FROM intentos_login WHERE fecha < now() - interval '1 day'`);
}

export async function borrarIntentos(ip) {
  await filas(`DELETE FROM intentos_login WHERE ip = $1`, [ip]);
}

/* ---------- Inicio ----------
   Se puede llamar muchas veces: solo trabaja la primera. */
let inicio;
export function inicializar() {
  return (inicio ??= (async () => {
    await (await db()).transaccion(async q => {
      // Evita que dos instancias creen las tablas al mismo tiempo
      await q(`SELECT pg_advisory_xact_lock(4815162342)`);
      await crearTablas(q);
      const yaIniciado = (await q(`SELECT 1 FROM configuracion WHERE clave = 'inicializado'`)).rows.length;
      if (!yaIniciado) {
        await cargarEjemplo(q);
        if (process.env.NODE_ENV !== "test") console.log("  Base de datos nueva: se cargaron los datos de ejemplo.");
      }
    });
  })().catch(e => { inicio = undefined; throw e; }));
}

export async function cerrar() {
  if (conexion) await (await conexion).cerrar();
  conexion = undefined;
  inicio = undefined;
}
